import { useEffect, useMemo, useRef, useState } from 'react'
import { seedProduct } from '../content/seed'
import { createEmailPreview } from '../services/emailTemplate'
import { enqueueRequest, listRequests, QueuePersistenceError } from '../services/requestQueue'

type Step = 'catalog' | 'preview' | 'saved'

export function Explorer({ onExit }: { onExit: () => void }) {
  const [step, setStep] = useState<Step>('catalog')
  const [name, setName] = useState('')
  const [email, setEmail] = useState('')
  const [error, setError] = useState('')
  const [pendingCount, setPendingCount] = useState(0)
  const [submitting, setSubmitting] = useState(false)
  const [openFeature, setOpenFeature] = useState(0)
  const modalCloseRef = useRef<HTMLButtonElement>(null)
  const preview = useMemo(() => createEmailPreview(seedProduct), [])
  useEffect(() => { void listRequests().then((items) => setPendingCount(items.length)) }, [])
  useEffect(() => { if (step !== 'catalog') modalCloseRef.current?.focus() }, [step])

  const submit = async () => {
    setError('')
    if (name.trim().length < 2) return setError('Enter a name with at least two characters.')
    if (!/^\S+@\S+\.\S+$/.test(email)) return setError('Enter a valid email address.')
    setSubmitting(true)
    try {
      await enqueueRequest({ name, email, productId: seedProduct.id })
      setPendingCount((await listRequests()).length)
      setStep('saved')
    } catch (failure) {
      setError(failure instanceof QueuePersistenceError && failure.reason === 'quota'
        ? 'This device storage is full. Ask an operator to free space; the request was not saved.'
        : 'Local storage is unavailable. The request was not saved; please ask an operator for help.')
    } finally { setSubmitting(false) }
  }

  return <main id="main-content" className="explorer">
    <header className="topbar"><button className="wordmark" onClick={onExit}>NEXUS</button><p>PRODUCT EXPLORER</p><span className="leidos-wordmark"><i aria-hidden="true">◆</i> leidos</span></header>
    <div className="explorer-grid">
      <aside className="market-nav"><p>LAND SYSTEMS</p><button className="selected"><span>01</span> JLTV overview</button><button disabled><span>02</span> Product pending</button><button disabled><span>03</span> Product pending</button><div className="queue-stat"><strong>{pendingCount}</strong><span>Requests saved locally</span><small>Sent: 0</small></div></aside>
      <section className="product-view">
        <div className="explorer-hero">
          <div className="product-copy"><p className="eyebrow">LAND SYSTEMS · DEMONSTRATION CONTENT</p><h1>{seedProduct.name}</h1><p className="lead">{seedProduct.description}</p><div className="hero-specs"><p>HIGHLIGHTS</p>{seedProduct.highlights.slice(0, 4).map((item, index) => <div key={item.text}><b>0{index + 1}</b><span>{item.text}</span></div>)}</div><button className="secondary-cta" onClick={() => setStep('preview')}>Share overview <span>→</span></button></div>
          <div className="product-visual"><img src="/assets/jltv-card.webp" alt="JLTV demonstrator in a studio setting" /><span>FILLER MEDIA</span><p>{seedProduct.heroLabel}</p></div>
        </div>
        <div className="feature-zone"><p className="eyebrow">FEATURES</p><div className="feature-accordion">{seedProduct.features.slice(0, 5).map((feature, index) => <button key={feature.text} aria-expanded={openFeature === index} onClick={() => setOpenFeature(index)}><span>Feature 0{index + 1}</span><b aria-hidden="true">{openFeature === index ? '−' : '+'}</b>{openFeature === index && <p>{feature.text}. This is demonstration-only content pending product-owner review.</p>}</button>)}</div></div>
      </section>
    </div>
    <button className="back-to-hub" onClick={onExit}>← Back to hub</button>
    {step !== 'catalog' && <div className="modal-backdrop"><section className="email-modal" role="dialog" aria-modal="true" aria-labelledby="email-modal-title">
      <button ref={modalCloseRef} className="close" onClick={() => setStep('catalog')} aria-label="Close follow-up request">×</button>
      {step === 'preview' ? <>
        <p className="eyebrow">AUTOGENERATED FOLLOW-UP</p><h2 id="email-modal-title">Take the overview with you.</h2><p className="modal-intro">Previewed from the selected Explorer product. The delivery service is not configured.</p>
        <div className="preview-window"><div className="preview-subject">{preview.subject}</div><div dangerouslySetInnerHTML={{ __html: preview.html }} /></div>
        <div className="visitor-fields"><label>Name<input value={name} onChange={(event) => setName(event.target.value)} autoComplete="name" /></label><label>Email<input value={email} onChange={(event) => setEmail(event.target.value)} type="email" autoComplete="email" /></label></div>
        {error && <p className="form-error" role="alert">{error}</p>}
        <button className="primary-cta full" onClick={submit} disabled={submitting}>{submitting ? 'Saving…' : 'Save request'} <span>→</span></button>
        <p className="privacy-note">Saved on this device only. No email is sent and no personal fields enter usage analytics.</p>
      </> : <div className="saved-state"><span>✓</span><p className="eyebrow">REQUEST SAVED</p><h2 id="email-modal-title">Pending — email service not configured.</h2><p>Your request is safely queued on this device. It has not been sent or delivered.</p><button className="primary-cta" onClick={() => { setName(''); setEmail(''); setStep('catalog') }}>Return to Explorer <span>→</span></button></div>}
    </section></div>}
  </main>
}
