import {chromium} from 'playwright-core'
import assert from 'node:assert/strict'
const b=await chromium.launch({executablePath:'/usr/bin/chromium',args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']})
try {
 const p=await b.newPage({viewport:{width:960,height:640},serviceWorkers:'block'})
 const errors=[];p.on('pageerror',e=>errors.push(e.message));p.on('console',m=>{if(m.type()==='error')errors.push(m.text())})
 let release;const gate=new Promise(r=>release=r)
 await p.route('**/jltv-runtime.glb',async route=>{await gate;await route.continue()})
 await p.goto(process.env.NEXUS_PREVIEW_URL ?? 'http://127.0.0.1:4177');await p.getByRole('button',{name:'Touch Screen to Begin'}).click();await p.locator('.hub-card-primary').click()
 await p.getByText('Loading',{exact:true}).waitFor()
 await p.waitForTimeout(1200)
 assert.equal((await p.locator('.experience-loading').innerText()).trim(),'Loading')
 assert.equal(await p.getByRole('button',{name:/^HUB$/}).count(),0)
 const hidden=await p.locator('.experience-content').evaluate(e=>({visibility:getComputedStyle(e).visibility,inert:e.inert}))
 assert.equal(hidden.visibility,'hidden');assert.equal(hidden.inert,true)
 const fill=await p.locator('.experience-progress > span').evaluate(e=>getComputedStyle(e).backgroundColor);assert.equal(fill,'rgb(115, 76, 221)')
 await p.screenshot({path:'/tmp/nexus-loading-screen.png'})
 console.log('Delayed asset: only Loading + purple progress bar; complete scene hidden and inert')
 release()
 await p.waitForFunction(()=>document.querySelector('.experience-content')?.dataset.ready==='true',null,{timeout:60000})
 await p.locator('.experience-loading').waitFor({state:'detached'})
 assert.equal(await p.locator('.experience-loading').count(),0)
 assert.equal(await p.locator('.model-stage').getAttribute('data-model-ready'),'true')
 const frames=Number(await p.locator('.model-stage').getAttribute('data-rendered-frames'));assert(frames>=3)
 assert(await p.getByRole('button',{name:/^HUB$/}).isVisible())
 await p.screenshot({path:'/tmp/nexus-loading-ready.png'})
 await p.getByRole('button',{name:/^HUB$/}).click();await p.locator('.hub-card-primary').click()
 await p.waitForFunction(()=>document.querySelector('.experience-content')?.dataset.ready==='true')
 await p.locator('.experience-loading').waitFor({state:'detached'})
 assert.equal(await p.locator('.experience-loading').count(),0)
 assert.deepEqual(errors,[])
 console.log('First GPU frames, fonts, warm-cache reentry and clean reveal passed; no browser/shader errors')
} finally {await b.close()}
